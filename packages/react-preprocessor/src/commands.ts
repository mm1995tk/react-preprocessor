/** Where the output of a command goes. Tests collect it; the executable writes it to the process streams */
export type IO = {
  stdout: (text: string) => void;
  stderr: (text: string) => void;
};

const USAGE = `Usage:
  react-preprocessor print <file> [--no-types] [--import-source <name>]
  react-preprocessor eject <dir|file>... [--write] [--types-file <path>] [--no-types] [--import-source <name>]

Commands:
  print   Write the plain React a file is rewritten to on standard output.
  eject   Rewrite files to plain React, to stop using react-preprocessor.
          Without --write it only lists the files that would change.

Options:
  --no-types              Do not ask the type checker which props are reactive (see \`types: false\`).
  --import-source <name>  The module the sugar is imported from (see \`importSource\`).
                          Defaults to \`react-preprocessor\`.
  --write                 eject: write the files.
  --types-file <path>     eject: the \`.ts\` file to write the plain types that replace \`Reactive<T>\` /
                          \`Derived<T>\` to. Defaults to \`reactive-types.ts\` in the directory of the
                          first argument.
  -h, --help              Show this message.
`;

/** The plain types that have the runtime shape of a reactive value that crosses a function boundary */
const TYPES_FILE = `// Generated by \`react-preprocessor eject\`.
// The shape a reactive value had at runtime when it crossed a function boundary.
export type Derived<T> = { value: T };
export type Reactive<T> = { value: T; update: (f: (old: T) => T) => void };
`;

/** Runs the command line. Returns the exit code */
export const run = (argv: string[], io: IO): number => {
  let args;
  try {
    args = parseArgs({
      args: argv,
      allowPositionals: true,
      allowNegative: true,
      options: {
        types: { type: "boolean", default: true },
        write: { type: "boolean" },
        "types-file": { type: "string" },
        "import-source": { type: "string", default: "react-preprocessor" },
        help: { type: "boolean", short: "h", default: false },
      },
    });
  } catch (error) {
    io.stderr(`${messageOf(error)}\n\n${USAGE}`);
    return 1;
  }

  const [command, ...targets] = args.positionals;
  const { write, "types-file": typesFile, "import-source": importSource } = args.values;
  if (args.values.help) {
    io.stdout(USAGE);
    return 0;
  }
  if (command === "print" && (write !== undefined || typesFile !== undefined)) {
    io.stderr(`print writes to standard output. --write and --types-file belong to eject.\n\n`);
    io.stderr(USAGE);
    return 1;
  }
  // One type checker for the whole run. It is slow to start
  const types = args.values.types ? createTypeService() : false;
  try {
    if (command === "print" && targets.length === 1) {
      return print(targets[0]!, { types, importSource }, io);
    }
    if (command === "eject" && targets.length > 0) {
      return eject(targets, { write: write ?? false, typesFile, types, importSource }, io);
    }
  } finally {
    if (types) types.close();
  }
  io.stderr(USAGE);
  return 1;
};

const messageOf = (error: unknown): string =>
  error instanceof Error ? error.message : String(error);

/** The options of the Babel plugin the commands pass on */
type TransformOptions = {
  types: TypeService | false;
  importSource: string;
};

/** The same parser plugins the Babel plugin turns on */
const parserPlugins = (filename: string): ("typescript" | "jsx")[] => [
  ...(/\.[cm]?tsx?$/.test(filename) ? (["typescript"] as const) : []),
  ...(/\.[jt]sx$/.test(filename) ? (["jsx"] as const) : []),
];

const babelOptions = (filename: string) => ({
  filename,
  babelrc: false,
  configFile: false,
  parserOpts: { plugins: parserPlugins(filename) },
});

/** Lowers the sugar in one file. Returns `null` when the preprocessor has nothing to rewrite */
const lower = (file: string, source: string, options: TransformOptions): string | null => {
  const babel = babelOptions(file);
  const result = transformSync(source, { ...babel, plugins: [[babelPlugin, options]] });
  // The plugin marks the files it rewrites. Most files of a project are not marked, and are done here
  const metadata = result?.metadata as { reactPreprocessor?: { lowered: boolean } } | undefined;
  if (result?.code == null || !metadata?.reactPreprocessor?.lowered) return null;
  // A file that only imports the types is marked too, and nothing in it is rewritten. Babel prints
  // the whole file again, so to tell, the output is compared with what Babel prints with no plugin
  if (result.code === transformSync(source, babel)?.code) return null;
  return `${result.code}\n`;
};

const print = (target: string, options: TransformOptions, io: IO): number => {
  const file = resolve(target);
  try {
    const source = readFileSync(file, "utf8");
    io.stdout(lower(file, source, options) ?? source);
    return 0;
  } catch (error) {
    // An error of the transform carries a code frame in its message
    io.stderr(`${messageOf(error)}\n`);
    return 1;
  }
};

/** The files the Babel and Vite plugins take as TypeScript, without declaration files */
const isSource = (name: string): boolean =>
  /\.[cm]?tsx?$/.test(name) && !/\.d\.[cm]?ts$/.test(name);

/**
 * The real path of a file that may not exist yet. Symbolic links are resolved everywhere, because
 * TypeScript resolves a relative import from the real location of the importing file.
 */
const real = (path: string): string => {
  const full = resolve(path);
  if (existsSync(full)) return realpathSync(full);
  const parent = dirname(full);
  return parent === full ? full : join(real(parent), basename(full));
};

/** The source files under the targets, without `node_modules`. Symbolic links are followed */
const collect = (targets: string[]): string[] => {
  const files = new Set<string>();
  /** Directories already walked. A link can point back to a parent */
  const walked = new Set<string>();
  const walk = (dir: string): void => {
    if (walked.has(dir)) return;
    walked.add(dir);
    for (const name of readdirSync(dir)) {
      const path = join(dir, name);
      let stats;
      try {
        // Follows a link. A `Dirent` says neither file nor directory for one
        stats = statSync(path);
      } catch {
        // A link to nothing
        continue;
      }
      if (stats.isDirectory()) {
        // Dot directories hold tool output (`.git`, `.next`), not sources
        if (name !== "node_modules" && !name.startsWith(".")) walk(realpathSync(path));
      } else if (stats.isFile() && isSource(name)) {
        files.add(realpathSync(path));
      }
    }
  };
  for (const target of targets) {
    const path = realpathSync(resolve(target));
    if (statSync(path).isDirectory()) walk(path);
    else if (isSource(basename(path))) files.add(path);
    else throw new Error(`${target} is not a TypeScript source file (.ts, .tsx, .mts, .cts).`);
  }
  return [...files].toSorted();
};

/** How the project writes the extension of a relative import: `./a.ts`, `./a.js`, or `./a` */
type Extension = ".ts" | ".js" | "";

/** A reference to the package found in a file, as a range of the module specifier (with its quotes) */
type Edit = { start: number; end: number; to: "types" | "jotai" };

type Scan = { edits: Edit[]; relatives: string[]; problems: string[] };

/** Calls `f` for every node under `node` */
const forEachNode = (node: t.Node, f: (node: t.Node) => void): void => {
  f(node);
  for (const key of t.VISITOR_KEYS[node.type] ?? []) {
    const child: unknown = (node as unknown as Record<string, unknown>)[key];
    for (const item of Array.isArray(child) ? child : [child]) {
      if (isNode(item)) forEachNode(item, f);
    }
  }
};

const isNode = (value: unknown): value is t.Node =>
  typeof value === "object" && value !== null && "type" in value;

const stringLiteral = (...candidates: unknown[]): t.StringLiteral | undefined =>
  candidates.find((value): value is t.StringLiteral => isNode(value) && t.isStringLiteral(value));

/**
 * Finds the references to the package that are left after lowering: static imports and re-exports,
 * dynamic `import()`, `import("...")` types, and `require()`.
 * They are replaced in the text, so that a file the preprocessor left alone keeps its formatting.
 * A reference that has no plain counterpart is a problem: the file would break once the package is gone.
 */
const scan = (file: string, code: string, importSource: string): Scan => {
  const found: Scan = { edits: [], relatives: [], problems: [] };
  const jotaiSource = `${importSource}/jotai`;
  const ast = parseSync(code, { ...babelOptions(file), sourceType: "module" });
  if (!ast) return found;

  /** `names` are what is taken from the module. `null` when that cannot be told, as in `await import(...)` */
  const refer = (node: t.Node, source: t.StringLiteral, names: string[] | null): void => {
    if (source.value.startsWith(".")) found.relatives.push(source.value);
    if (source.value !== importSource && source.value !== jotaiSource) return;
    const edit = { start: source.start!, end: source.end! };
    // The Jotai hooks are copied as a whole module
    if (source.value === jotaiSource) {
      found.edits.push({ ...edit, to: "jotai" });
      return;
    }
    // Only the two types have a plain counterpart. The values are gone after lowering
    const unknown = (names ?? ["*"]).filter((name) => name !== "Reactive" && name !== "Derived");
    if (unknown.length === 0) {
      found.edits.push({ ...edit, to: "types" });
      return;
    }
    const what = names
      ? unknown.map((name) => `\`${name}\``).join(", ")
      : "what this expression loads";
    found.problems.push(
      `${file}:${node.loc?.start.line ?? 0}: eject cannot replace ${what} from "${importSource}". ` +
        "Only the types `Reactive` and `Derived` have a plain counterpart.",
    );
  };

  forEachNode(ast.program, (node) => {
    // Node shapes differ between Babel versions, so the fields are read loosely
    const fields = node as unknown as Record<string, unknown>;
    if (t.isImportDeclaration(node)) {
      const names = node.specifiers.map((specifier) =>
        t.isImportSpecifier(specifier) ? nameOf(specifier.imported) : "*",
      );
      refer(node, node.source, names);
    } else if (t.isExportNamedDeclaration(node) && node.source) {
      const names = node.specifiers.map((specifier) =>
        t.isExportSpecifier(specifier) ? nameOf(specifier.local) : "*",
      );
      refer(node, node.source, names);
    } else if (t.isExportAllDeclaration(node)) {
      refer(node, node.source, ["*"]);
    } else if (node.type === "ImportExpression") {
      const source = stringLiteral(fields.source);
      if (source) refer(node, source, null);
    } else if (t.isCallExpression(node)) {
      const callee = node.callee;
      const loads = callee.type === "Import" || t.isIdentifier(callee, { name: "require" });
      const source = stringLiteral(node.arguments[0]);
      if (loads && source) refer(node, source, null);
    } else if (node.type === "TSImportType") {
      // `import("react-preprocessor").Reactive<T>`
      const argument = isNode(fields.argument) ? fields.argument : undefined;
      const literal = (argument as { literal?: unknown } | undefined)?.literal;
      const source = stringLiteral(fields.source, argument, literal);
      const qualifier = fields.qualifier;
      const name = isNode(qualifier) && t.isIdentifier(qualifier) ? qualifier.name : "*";
      if (source) refer(node, source, [name]);
    }
  });
  return found;
};

const nameOf = (node: t.Identifier | t.StringLiteral): string =>
  t.isIdentifier(node) ? node.name : node.value;

/** Follows the imports the project already has. `.ts` when they do not tell */
const extensionOf = (relatives: string[]): Extension => {
  const count = { ".ts": 0, ".js": 0, "": 0 };
  for (const specifier of relatives) {
    if (/\.[cm]?tsx?$/.test(specifier)) count[".ts"] += 1;
    else if (/\.[cm]?jsx?$/.test(specifier)) count[".js"] += 1;
    // Other extensions are assets, such as `./style.css`
    else if (!/\.\w+$/.test(specifier)) count[""] += 1;
  }
  if (count[""] > count[".ts"] && count[""] >= count[".js"]) return "";
  return count[".js"] > count[".ts"] ? ".js" : ".ts";
};

/** The module specifier that reaches the generated file `target` (a `.ts` file) from `from` */
const specifierTo = (from: string, target: string, extension: Extension): string => {
  const path = relative(dirname(from), target).split(sep).join("/");
  const bare = path.replace(/\.ts$/, "");
  return `${bare.startsWith(".") ? "" : "./"}${bare}${extension}`;
};

const NEXT_STEPS = `
Next steps:
  1. Run your formatter. The rewritten files lost their formatting (comments are kept).
  2. Remove the preprocessor from your build config:
       Vite     \`reactPreprocessor()\` from \`plugins\`
       Next.js  the \`react-preprocessor/loader\` rules and the \`react-preprocessor/jsx-runtime\` aliases
       Babel    \`react-preprocessor/babel\` from \`plugins\`
  3. Remove \`"jsxImportSource": "react-preprocessor"\` from tsconfig.json.
  4. Run the type checker, then uninstall react-preprocessor.
`;

export type EjectOptions = TransformOptions & {
  write: boolean;
  /** Where the plain types go. Defaults to `reactive-types.ts` in the directory of the first target */
  typesFile: string | undefined;
};

/** Rewrites the files under the targets to plain React. Returns the exit code */
export const eject = (targets: string[], options: EjectOptions, io: IO): number => {
  const problems: string[] = [];
  let files: string[];
  let typesFile: string;
  try {
    files = collect(targets);
    const first = real(targets[0]!);
    typesFile = real(
      options.typesFile ??
        join(statSync(first).isDirectory() ? first : dirname(first), "reactive-types.ts"),
    );
    // The imports are written from this name. With another extension they would not reach the file
    if (!typesFile.endsWith(".ts") || typesFile.endsWith(".d.ts")) {
      throw new Error(`--types-file must be a .ts file, but got ${options.typesFile}.`);
    }
  } catch (error) {
    io.stderr(`${messageOf(error)}\n`);
    return 1;
  }
  const jotaiFile = join(dirname(typesFile), "reactive-jotai.ts");

  // An error of the type checker itself (TypeScript 7 is missing, no tsconfig covers the file) is not
  // about one file: every file after it would report the same. It is told apart from a transform error here
  let typeCheckerError: unknown;
  const service = options.types;
  const types: TypeService | false = service && {
    query(...args) {
      try {
        return service.query(...args);
      } catch (error) {
        typeCheckerError = error;
        throw error;
      }
    },
    invalidate: () => service.invalidate(),
    close: () => service.close(),
  };

  // Everything is computed before anything is written: one failure leaves the project untouched
  const results: { file: string; lowered: boolean; code: string; edits: Edit[] }[] = [];
  const relatives: string[] = [];
  for (const file of files) {
    try {
      const source = readFileSync(file, "utf8");
      const lowered = lower(file, source, { types, importSource: options.importSource });
      const code = lowered ?? source;
      const found = scan(file, code, options.importSource);
      problems.push(...found.problems);
      relatives.push(...found.relatives);
      results.push({ file, lowered: lowered !== null, code, edits: found.edits });
    } catch (error) {
      if (typeCheckerError !== undefined) {
        problems.push(
          `${messageOf(typeCheckerError)}\n` +
            "The type checker could not be used, so eject stopped at the first file that needs it. " +
            "Fix this, or pass --no-types.",
        );
        break;
      }
      problems.push(messageOf(error));
    }
  }

  const extension = extensionOf(relatives);
  const usesJotai = results.some(({ edits }) => edits.some((edit) => edit.to === "jotai"));
  const usesTypes = usesJotai || results.some(({ edits }) => edits.length > 0);

  /** Files to write. Keyed by path */
  const rewritten = new Map<string, string>();
  for (const { file, lowered, code, edits } of results) {
    let output = code;
    // From the end, so that the earlier ranges stay valid
    for (const edit of edits.toSorted((a, b) => b.start - a.start)) {
      const target = edit.to === "jotai" ? jotaiFile : typesFile;
      const quote = output[edit.start];
      output = `${output.slice(0, edit.start)}${quote}${specifierTo(file, target, extension)}${quote}${output.slice(edit.end)}`;
    }
    if (lowered || edits.length > 0) rewritten.set(file, output);
  }

  const created = new Map<string, string>();
  const create = (file: string, content: string): void => {
    if (!existsSync(file)) created.set(file, content);
    else if (readFileSync(file, "utf8") !== content) {
      problems.push(
        `${file} already exists with other content. Move it, or choose another place with --types-file.`,
      );
    }
  };
  if (usesTypes) create(typesFile, TYPES_FILE);
  if (usesJotai) create(jotaiFile, jotaiSource(specifierTo(jotaiFile, typesFile, extension)));

  if (problems.length > 0) {
    io.stderr(`${problems.join("\n\n")}\n\n`);
    io.stderr(`eject failed with ${count(problems.length, "error")}. No file was written.\n`);
    return 1;
  }
  if (rewritten.size === 0) {
    io.stdout(`Nothing to eject: no file uses ${options.importSource}.\n`);
    return 0;
  }

  if (!options.write) {
    io.stdout(`Would rewrite ${count(rewritten.size, "file")}:\n${list(rewritten.keys())}`);
    if (created.size > 0) io.stdout(`Would create:\n${list(created.keys())}`);
    io.stdout("\nNothing was written. Run again with --write to apply.\n");
    return 0;
  }

  for (const [file, content] of [...created, ...rewritten]) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, content);
  }
  io.stdout(`Rewrote ${count(rewritten.size, "file")}:\n${list(rewritten.keys())}`);
  if (created.size > 0) io.stdout(`Created:\n${list(created.keys())}`);
  io.stdout(NEXT_STEPS);
  return 0;
};

const count = (n: number, noun: string): string => `${n} ${noun}${n === 1 ? "" : "s"}`;

/** One path per line, relative to the working directory */
const list = (paths: Iterable<string>): string => {
  const cwd = realpathSync(process.cwd());
  return [...paths].map((path) => `  ${relative(cwd, path) || path}\n`).join("");
};

/**
 * The source of `react-preprocessor/jotai`, with its types pointed at the generated types file.
 * It is the only runtime code of the package, so ejecting copies it into the project.
 */
const jotaiSource = (typesSpecifier: string): string => {
  const own = `from "./index.ts"`;
  if (!jotaiTemplate.includes(own)) throw new Error("eject: unexpected content in src/jotai.ts.");
  return jotaiTemplate.replace(own, `from "${typesSpecifier}"`);
};
